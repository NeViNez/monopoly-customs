export function affected(cells, cell, selector) {
  if (!selector) return false;
  if (selector.type) return selector.type === cell.type;
  if (cell.type !== "street") return false;
  if (selector.group !== undefined) return selector.group === cell.group;
  return (
    cells
      .filter((b) => b.type === "street" && b.group === cell.group)
      .findIndex((b) => b.index === cell.index) +
      1 ===
    selector.position
  );
}
